-- ==================================================
-- 示例 1 最小修改任务参考答案
-- ==================================================
SELECT employee_name, salary
FROM employees
WHERE salary < 10000;
-- 为什么这样写：小于号表示严格低于，不包含 10000。
-- 预期结果特征：2 列；每行 salary 都低于 10000。
-- 验证方法：检查最高的返回薪资仍小于 10000。
-- 常见错误：写成 <= 10000，改变了边界含义。

-- ==================================================
-- 示例 2 最小修改任务参考答案
-- ==================================================
SELECT employee_name, department_id, salary
FROM employees
WHERE department_id = 3
  AND salary >= 10000;
-- 为什么这样写：两个条件必须同时成立。
-- 预期结果特征：部门均为 3，薪资不低于 10000。
-- 验证方法：逐列检查部门和薪资下限。
-- 常见错误：用 OR 导致其他行进入结果。

-- ==================================================
-- 示例 3 最小修改任务参考答案
-- ==================================================
SELECT project_name, project_status, budget
FROM projects
WHERE (project_status = '已完成' OR project_status = '暂停')
  AND budget >= 300000;
-- 为什么这样写：括号把两种状态作为一个整体，再应用预算条件。
-- 预期结果特征：只有两种目标状态，预算均达下限。
-- 验证方法：分别检查状态和预算。
-- 常见错误：去掉括号，使 AND 只约束第二个状态。

-- ==================================================
-- 示例 4 最小修改任务参考答案
-- ==================================================
SELECT employee_name, department_id
FROM employees
WHERE department_id IN (1, 4);
-- 为什么这样写：IN 列出两个允许的部门编号。
-- 预期结果特征：只有部门 1 或 4 的员工。
-- 验证方法：逐行检查 department_id。
-- 常见错误：漏写 IN 后的括号。

-- ==================================================
-- 示例 5 最小修改任务参考答案
-- ==================================================
SELECT employee_name, salary
FROM employees
WHERE salary BETWEEN 9500 AND 13500
ORDER BY salary ASC;
-- 为什么这样写：BETWEEN 保留两个边界及中间值。
-- 预期结果特征：薪资从 9500 到 13500，包含端点。
-- 验证方法：检查第一行、最后一行和所有中间值。
-- 常见错误：把高边界写在低边界前。

-- ==================================================
-- 示例 6 最小修改任务参考答案
-- ==================================================
SELECT employee_name, job_title
FROM employees
WHERE job_title LIKE '%专员%';
-- 为什么这样写：关键词两侧的百分号表示任意位置包含。
-- 预期结果特征：所有职位文本都包含“专员”。
-- 验证方法：逐行检查 job_title 中的关键词位置。
-- 常见错误：只在关键词一侧写百分号。

-- ==================================================
-- 示例 7 最小修改任务参考答案
-- ==================================================
SELECT project_name, project_status, end_date
FROM projects
WHERE end_date IS NOT NULL
  AND project_status NOT IN ('暂停');
-- 为什么这样写：IS NOT NULL 保留已有日期的行，NOT IN 排除暂停。
-- 预期结果特征：结束日期无 NULL，状态没有“暂停”。
-- 验证方法：检查 end_date 和 project_status 两列。
-- 常见错误：使用 <> NULL。

-- ==================================================
-- 练习 1 参考答案
-- ==================================================
SELECT employee_name, department_id
FROM employees
WHERE department_id = 2;
-- 为什么这样写：等值条件只保留部门编号为 2 的员工。
-- 预期结果特征：2 列，department_id 全为 2。
-- 常见错误：把数字 2 写成字段名。
-- 验证方法：检查列数和每行部门编号。

-- ==================================================
-- 练习 2 参考答案
-- ==================================================
SELECT project_name, end_date
FROM projects
WHERE end_date IS NULL;
-- 为什么这样写：NULL 必须用 IS NULL 判断。
-- 预期结果特征：2 列，end_date 全为 NULL。
-- 常见错误：写 end_date = NULL。
-- 验证方法：观察目标列是否全部显示空值。

-- ==================================================
-- 练习 3 参考答案
-- ==================================================
SELECT employee_name, department_id, salary
FROM employees
WHERE department_id IN (1, 3)
  AND salary >= 10000;
-- 为什么这样写：IN 表示允许两个部门，AND 加上共同薪资下限。
-- 预期结果特征：部门仅为 1 或 3，薪资均达 10000。
-- 常见错误：在 IN 列表外遗漏括号。
-- 验证方法：分别检查部门集合和薪资最小值。

-- ==================================================
-- 练习 4 参考答案
-- ==================================================
SELECT project_name, project_status, budget
FROM projects
WHERE budget BETWEEN 600000 AND 900000
  AND project_status = '进行中';
-- 为什么这样写：BETWEEN 包含上下边界，AND 要求状态同时符合。
-- 预期结果特征：3 列；预算在范围内且状态统一。
-- 常见错误：把低值和高值写反。
-- 验证方法：检查最小、最大预算和状态列。

-- ==================================================
-- 练习 5 参考答案
-- ==================================================
SELECT employee_name, department_id, job_title
FROM employees
WHERE job_title LIKE '%专员%'
  AND NOT (department_id = 4);
-- 为什么这样写：双百分号匹配任意位置包含，NOT 排除部门 4。
-- 预期结果特征：职位含“专员”，无部门 4。
-- 常见错误：写 LIKE '专员'，只能匹配完全相等文本。
-- 验证方法：检查职位文本和部门编号。

-- ==================================================
-- 练习 6 参考答案
-- ==================================================
SELECT project_id, project_name, project_status, budget
FROM projects
WHERE (project_status = '进行中' OR project_status = '待启动')
  AND budget > 800000;
-- 为什么这样写：括号使两种状态共同受到严格预算下限约束。
-- 预期结果特征：4 列；预算都大于 800000。
-- 常见错误：使用 >=，误把边界也包含进来。
-- 验证方法：检查状态集合和最低预算。

-- ==================================================
-- 练习 7 参考答案
-- ==================================================
SELECT project_name, project_status, end_date
FROM projects
WHERE end_date IS NOT NULL
  AND project_status NOT IN ('已完成', '暂停');
-- 为什么这样写：非空与状态排除必须同时满足。
-- 预期结果特征：无 NULL 日期，也无两种排除状态。
-- 常见错误：写 NOT project_status IN (...) 造成可读性差或位置错误。
-- 验证方法：同时检查日期和状态列。

-- ==================================================
-- 练习 8 参考答案
-- ==================================================
SELECT project_name, project_status, budget
FROM projects
WHERE (project_status = '进行中' OR project_status = '待启动')
  AND budget >= 700000;
-- 是否报错：原 SQL 语法完整，通常不会报错。
-- 结果是否正确：不正确；AND 优先计算，只约束“待启动”分支。
-- 如何修改：用括号把两个状态组合，再与预算条件用 AND 连接。
-- 修改后特征：两种状态的预算都不低于 700000。
-- 常见错误：认为缩进会改变逻辑优先级。
-- 验证方法：特别检查所有“进行中”项目的预算。
