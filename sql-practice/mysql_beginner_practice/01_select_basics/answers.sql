SELECT
    project_name AS project,
    budget AS project_budget
FROM projects
ORDER BY
    budget DESC,
    project_name ASC
LIMIT 3;

-- 为什么这样写：
-- AS 设置结果列标题；排序先确定最高预算，并用项目名称处理并列。
-- 预期结果特征：
-- 结果列标题为 project 和 project_budget，最多 3 行，预算从高到低。
-- 常见错误：
-- 只写 LIMIT，或把预算排成升序。
-- 验证方法：
-- 检查列标题、行数、预算方向和并列时的项目名称。

