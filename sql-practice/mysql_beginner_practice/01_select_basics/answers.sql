SELECT
    project_name,
    budget,
    budget * 0.05 AS budget_fee
FROM projects
ORDER BY
    budget_fee DESC,
    project_name ASC;

-- 为什么这样写：
-- 计算表达式生成预算的百分之五，随后按计算结果稳定排序。
-- 预期结果特征：
-- 3 列，每个项目一行，budget_fee 从高到低。
-- 常见错误：
-- 忘记 AS 别名或使用整数 5 代替 0.05。
-- 验证方法：
-- 手工核对至少一行，检查排序，并确认原 budget 没变化。

