SELECT
    employee_name,
    salary
FROM employees
ORDER BY
    salary DESC,
    employee_name ASC
LIMIT 3;

-- 是否报错：
-- 原 SQL 语法完整，通常不会报错。
-- 结果是否正确：
-- 不正确。没有 ORDER BY 的前三行不代表薪资最高三人。
-- 如何修改：
-- salary DESC 定义最高在前，employee_name ASC 处理并列，再 LIMIT 3。
-- 修改后特征：
-- 最多 3 行，薪资从高到低；同薪资时姓名升序。
-- 预期结果特征：
-- 最多 3 行，2 列，薪资从高到低。
-- 常见错误：
-- 认为 SQL 能运行就代表结果正确。
-- 验证方法：
-- 检查相邻薪资和同薪资时的姓名顺序。
